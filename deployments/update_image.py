"""Record a successfully published image and its Kustomize deployment digest."""
import json
import os
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
image = os.environ["IMAGE"]
digest = os.environ["DIGEST"]
commit = os.environ["SOURCE_COMMIT"]
if not re.fullmatch(r"ghcr\.io/[a-z0-9._-]+/[a-z0-9._/-]+", image):
    raise SystemExit("Expected a lowercase GHCR image name without a tag")
if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
    raise SystemExit("Invalid image digest")
if not re.fullmatch(r"[0-9a-f]{40}", commit):
    raise SystemExit("Invalid source commit")
record = {"image": image, "tag": "personal", "digest": digest,
          "sourceCommit": commit, "platforms": ["linux/amd64", "linux/arm64"]}
(root / "deployments/image.json").write_text(json.dumps(record, indent=2) + "\n")
# This file is generated by the release workflow. Keep resource changes here too.
(root / "deployments/k8s/kustomization.yaml").write_text(
    "apiVersion: kustomize.config.k8s.io/v1beta1\n"
    "kind: Kustomization\n\n"
    "resources:\n  - deployment.yaml\n  - service.yaml\n\n"
    "images:\n  - name: memos\n"
    f"    newName: {json.dumps(image)}\n"
    f"    digest: {json.dumps(digest)}\n"
)
